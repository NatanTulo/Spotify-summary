import { expect, test, type Page } from '@playwright/test'

async function expectNoHorizontalOverflow(page: Page) {
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}

async function choose(page: Page, label: string, option: string) {
    await page.getByRole('combobox', { name: label, exact: true }).click()
    await page.getByRole('option', { name: option, exact: true }).click()
}

test('local import → profile → search → chart, date scope and mobile', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width: 1920, height: 1080 })
    await page.addInitScript(() => localStorage.setItem('theme', 'dark'))
    await page.goto('/')
    await expect(page.locator('html')).toHaveClass(/dark/)
    await expect(page.getByRole('button', { name: /log.?in|zaloguj/i })).toHaveCount(0)
    await page.getByRole('button', { name: 'Dane i import', exact: true }).click()
    await expect(page).toHaveURL(/\/data$/)
    const main = page.getByRole('main')
    await expect(main.getByRole('heading', { name: 'Dane i import', exact: true })).toBeVisible()
    await expect(main.getByRole('heading', { name: 'E2E', exact: true })).toBeVisible()
    await main.getByRole('button', { name: 'Importuj', exact: true }).click()
    const profile = main.getByRole('button', { name: 'E2E', exact: true })
    await expect(profile).toBeVisible({ timeout: 20_000 })
    await profile.click()
    await expect(page.getByRole('combobox', { name: 'Wybór Profilu' })).toHaveText('E2E')

    await page.getByRole('navigation', { name: 'Nawigacja główna' }).getByRole('link', { name: 'Muzyka', exact: true }).click()
    const trackTable = page.getByRole('table')
    await expect(trackTable.getByRole('button', { name: 'Needle', exact: true })).toBeVisible()
    await expect(trackTable.getByRole('button', { name: 'Different', exact: true })).toBeVisible()
    const firstRow = trackTable.locator('tbody tr').first()
    expect((await firstRow.boundingBox())!.y).toBeLessThanOrEqual(360)
    await expectNoHorizontalOverflow(page)
    await page.screenshot({ path: 'test-results/music-dark-desktop.png', fullPage: true })

    // Search applies after the pause, without an extra Search/Apply action.
    await page.getByPlaceholder('Szukaj utworów, artystów lub albumów...').fill('Needle')
    await expect(page).toHaveURL(/musicSearch=Needle/)
    await expect(trackTable.getByRole('cell', { name: /Needle/ }).first()).toBeVisible()
    await expect(trackTable.getByRole('cell', { name: /Different/ })).toHaveCount(0)
    const trackButton = trackTable.getByRole('button', { name: 'Needle', exact: true })
    const selectedRow = trackTable.locator('tbody tr').filter({ has: page.getByRole('button', { name: 'Needle', exact: true }) })
    await selectedRow.getByRole('cell').nth(1).click()
    const details = page.getByRole('region', { name: 'Szczegóły utworu' })
    await expect(details).toBeVisible()
    await expect(page).toHaveURL(/track=\d+/)
    // Inline details inherit the track identity from the selected table row.
    await expect(details.getByRole('heading', { name: 'Needle', exact: true })).toHaveCount(0)
    const chart = details.getByTestId('track-timeline-chart')
    await expect(chart).toBeVisible()
    expect((await details.boundingBox())!.y).toBeGreaterThan((await selectedRow.boundingBox())!.y)
    expect((await chart.boundingBox())!.width).toBeGreaterThan(1400)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(details).toHaveCount(0)
    await expect(selectedRow).toBeFocused()
    await expect(page).toHaveURL(/musicSearch=Needle/)
    expect(new URL(page.url()).searchParams.has('track')).toBe(false)
    await trackButton.click()
    await expect(details).toBeVisible()
    await page.goBack()
    await expect(details).toHaveCount(0)
    await expect(trackButton).toBeFocused()
    await expect(page.getByPlaceholder('Szukaj utworów, artystów lub albumów...')).toHaveValue('Needle')
    await expect(trackTable.getByRole('cell', { name: /Different/ })).toHaveCount(0)

    await page.getByRole('tab', { name: 'Wykresy', exact: true }).click()
    await expect(page).toHaveURL(/tab=charts/)
    await expect(page.locator('.recharts-wrapper').first()).toBeVisible()
    const timelineHeading = page.getByRole('heading', { name: 'Historia słuchania', exact: true })
    await expect(timelineHeading).toBeVisible()
    const timelineCard = page.locator(`[aria-labelledby="${await timelineHeading.getAttribute('id')}"]`)
    await timelineCard.getByText('Pokaż dane w tabeli', { exact: true }).click()
    const timeline = timelineCard.getByRole('table', { name: /Dane dzienne dla widocznego zakresu/ })
    await expect(timeline.getByRole('row', { name: '2026-10-01 2 2', exact: true })).toBeVisible()
    for (const path of ['/podcasts', '/audiobooks']) {
        await page.goto(path)
        await expect(page.getByRole('main').getByRole('heading', { level: 1 })).toBeVisible()
        await expect(page.getByRole('alert')).toHaveCount(0)
    }
    await page.goto('/')
    await expect(page.getByRole('heading', { name: 'Twoja historia w czasie' })).toBeVisible()
    const period = page.getByRole('combobox', { name: 'Wybierz okres' })
    await choose(page, 'Wybierz okres', '2026')
    await expect(period).toHaveText('2026')
    expect(new URL(page.url()).searchParams.get('dateFrom')).toBe('2026-01-01')
    expect(new URL(page.url()).searchParams.get('dateTo')).toBe('2026-12-31')
    await expect(page.getByText('Okres A: 2026-01-01 – 2026-12-31', { exact: false })).toBeVisible()
    await expect(page.getByRole('button', { name: /2026-09-01: 1 odtworzenie/ })).toBeEnabled()
    await page.goBack()
    await expect(period).toHaveText('Cała historia')
    expect(new URL(page.url()).searchParams.has('dateFrom')).toBe(false)
    await choose(page, 'Wybierz okres', 'Własny zakres')
    await page.getByLabel('Data od', { exact: true }).fill('2026-10-01')
    await page.getByLabel('Data do', { exact: true }).fill('2026-10-01')
    await page.getByRole('button', { name: 'Zastosuj', exact: true }).click()
    await expect(page.getByText('Okres A: 2026-10-01 – 2026-10-01', { exact: false })).toBeVisible()
    await expect(page.getByRole('button', { name: /2026-10-01: 2 odtworzenia/ })).toBeAttached()
    await expect(page.getByRole('button', { name: /2026-09-01: 1 odtworzenie/ })).toBeEnabled()
    await choose(page, 'Rok kalendarza', '2024')
    await expect(page.getByRole('button', { name: /2024-03-15: 1 odtworzenie/ })).toBeEnabled()
    expect(new URL(page.url()).searchParams.get('dateFrom')).toBe('2026-10-01')
    await expect(page.getByText('Okres A: 2026-10-01 – 2026-10-01', { exact: false })).toBeVisible()
    await page.setViewportSize({ width: 390, height: 844 })
    await expect(period).toBeVisible()
    await expectNoHorizontalOverflow(page)
    await page.screenshot({ path: 'test-results/history-mobile.png', fullPage: true })

    await page.getByRole('navigation', { name: 'Nawigacja główna' }).getByRole('link', { name: 'Muzyka', exact: true }).click()
    expect(new URL(page.url()).searchParams.get('dateFrom')).toBe('2026-10-01')
    expect(new URL(page.url()).searchParams.get('dateTo')).toBe('2026-10-01')
    const tabs = page.getByRole('tablist').getByRole('tab')
    await expect(tabs).toHaveCount(5)
    const boxes = []
    for (const tab of await tabs.all()) {
        await expect(tab).toBeVisible()
        boxes.push((await tab.boundingBox())!)
    }
    for (let i = 0; i < boxes.length; i++) for (let j = i + 1; j < boxes.length; j++) {
        const a = boxes[i], b = boxes[j]
        expect(a.x + a.width <= b.x + 1 || b.x + b.width <= a.x + 1 || a.y + a.height <= b.y + 1 || b.y + b.height <= a.y + 1).toBe(true)
    }
    await expect(page.getByRole('button', { name: /Needle/ })).toBeVisible()
    await expect(page.getByRole('table')).toHaveCount(0)
    await expectNoHorizontalOverflow(page)
    await page.getByRole('button', { name: /Needle/ }).click()
    await expect(details).toBeVisible()
    expect((await details.boundingBox())!.width).toBeGreaterThan(300)
    await expectNoHorizontalOverflow(page)
    await page.getByRole('button', { name: /Needle/ }).click()
    await expect(details).toHaveCount(0)
    await page.screenshot({ path: 'test-results/music-dark-mobile.png', fullPage: true })
    expect(errors).toEqual([])
})

test('accent colors persist and chart zoom can scope rankings independently', async ({ page }) => {
    await page.setViewportSize({ width: 1920, height: 1080 })
    await page.goto('/')
    const colors = page.getByLabel('Kolory interfejsu', { exact: true })
    await colors.click()
    await page.getByRole('button', { name: 'Niebieski', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Niebieski', exact: true })).toHaveAttribute('aria-pressed', 'true')
    const blue = await page.evaluate(() => ({ primary: getComputedStyle(document.documentElement).getPropertyValue('--primary'), background: getComputedStyle(document.documentElement).getPropertyValue('--background') }))
    await page.getByRole('button', { name: 'Bursztynowy', exact: true }).click()
    await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--primary'))).not.toBe(blue.primary)
    await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--background'))).not.toBe(blue.background)
    await page.reload()
    await colors.click()
    await expect(page.getByRole('button', { name: 'Bursztynowy', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await page.keyboard.press('Escape')
    const tracks = page.getByRole('region', { name: 'Najpopularniejsze utwory', exact: true })
    await expect(tracks.getByText('Archive', { exact: true })).toBeVisible()
    await choose(page, 'Powiększ od', '2026-10-01')
    await expect(tracks.getByText('Needle', { exact: true })).toBeVisible()
    await expect(tracks.getByText('Different', { exact: true })).toHaveCount(0)
    await expect(tracks.getByText('Archive', { exact: true })).toHaveCount(0)
    expect(new URL(page.url()).searchParams.has('dateFrom')).toBe(false)
    await page.getByRole('checkbox', { name: 'Dopasuj rankingi do zakresu wykresu' }).uncheck()
    await expect(tracks.getByText('Different', { exact: true })).toBeVisible()
    await expect(tracks.getByText('Archive', { exact: true })).toBeVisible()
    await page.getByRole('checkbox', { name: 'Dopasuj rankingi do zakresu wykresu' }).check()
    await expect(tracks.getByText('Archive', { exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: /Reset/ }).click()
    await expect(tracks.getByText('Archive', { exact: true })).toBeVisible()
})

test('production CSP allows local scripts and fonts without unsafe script permissions', async ({ request }) => {
    const response = await request.get('/')
    const csp = response.headers()['content-security-policy']
    expect(csp).toContain("script-src 'self'")
    expect(csp).not.toContain('unsafe-eval')
    expect(csp).not.toMatch(/script-src[^;]*unsafe-inline/)
    expect(await response.text()).not.toContain('fonts.googleapis.com')
})

test('failed API is visible and retry recovers', async ({ page }) => {
    await page.route('**/api/stats/overview*', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ success: false, code: 'TEST_FAILURE', error: 'Test API unavailable' }) }))
    await page.goto('/')
    await expect(page.getByRole('alert').filter({ hasText: 'Test API unavailable' })).toBeVisible()
    await page.unroute('**/api/stats/overview*')
    await page.getByRole('alert').filter({ hasText: 'Test API unavailable' }).getByRole('button', { name: 'Spróbuj ponownie' }).click()
    await expect(page.getByRole('alert')).toHaveCount(0)
})
